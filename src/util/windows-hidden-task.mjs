/**
 * Windows background tasks without popups (v1.6.5).
 *
 * ## The problem this fixes
 *
 * The standby keeper and the fleet watcher were scheduled with
 * `schtasks /TR "node.exe script.mjs"`. Windows Task Scheduler runs such a command in the
 * interactive session, which creates a **console window every time the task fires** — a 2-minute
 * keeper means a window every two minutes, and a 5-minute watcher that itself runs for hours
 * accumulates both windows and processes. That is a real usability defect: the operator sees the
 * machine "randomly opening windows" and cannot tell what is happening.
 *
 * ## The fix
 *
 * `wscript.exe //B wrapper.vbs` runs invisibly. The wrapper (VBScript) starts the real command with
 * `WScript.Shell.Run(command, 0, False)`: window style 0 = hidden, third argument = do not wait. No
 * console window, no lingering `cmd`, and the task still runs on schedule.
 *
 * Everything here is pure string construction (and one CLI that calls `schtasks`), so the escaping
 * rules — the part that silently breaks hidden wrappers — are unit-testable without touching a real
 * scheduler.
 */

/**
 * Command line for Task Scheduler that hides the window.
 *
 * @param {string} vbsPath Absolute path of the wrapper .vbs.
 * @returns {string} e.g. `wscript.exe //B "C:\...\wrapper.vbs"`
 */
export function hiddenTaskCommandLine(vbsPath) {
  if (typeof vbsPath !== 'string' || vbsPath.trim() === '') throw new TypeError('vbsPath is required');
  return `wscript.exe //B "${vbsPath}"`;
}

/** Escape one literal for the inside of a VBScript double-quoted string. */
export function vbsString(value) {
  return '"' + String(value).replace(/"/g, '""') + '"';
}

/**
 * Build the wrapper script that runs `command` hidden.
 *
 * The command itself is passed through verbatim, and `arguments` is appended in the same
 * double-quote-escaped form Windows uses on the command line (`""` inside a VBS string becomes one
 * literal quote when the shell rebuilds the command). Every argument is quoted individually so a
 * path with spaces cannot split into two arguments.
 *
 * @param {{command: string, args?: string[], workingDirectory?: string|null}} input
 * @returns {string} VBScript source.
 */
export function buildHiddenWrapper({ command, args = [], workingDirectory = null }) {
  if (typeof command !== 'string' || command.trim() === '') throw new TypeError('command is required');
  // Build the real command line first (Windows quoting), THEN escape the whole line once for
  // VBScript. Escaping each argument separately and escaping again for the script string would
  // double the quotes twice — the subtle over-escaping that makes a wrapper run the wrong token.
  const quoteWin = (value) => (/[\s"]/.test(String(value)) ? '"' + String(value).replace(/"/g, '\\"') + '"' : String(value));
  const parts = [quoteWin(command), ...(Array.isArray(args) ? args : []).map(quoteWin)];
  const lines = [
    "' Generated by w2m-hidden-task (v1.6.5): run a command with NO console window.",
    'Set sh = CreateObject("WScript.Shell")',
  ];
  if (typeof workingDirectory === 'string' && workingDirectory !== '') {
    lines.push(`sh.CurrentDirectory = ${vbsString(workingDirectory)}`);
  }
  lines.push(`sh.Run ${vbsString(parts.join(' '))}, 0, False`);
  return lines.join('\r\n') + '\r\n';
}

/**
 * The `schtasks /Create` argument list for a hidden wrapper, without executing anything.
 *
 * @param {{taskName: string, everyMinutes: number, vbsPath: string}} input
 * @returns {string[]}
 */
export function hiddenTaskArgs({ taskName, everyMinutes, vbsPath }) {
  if (typeof taskName !== 'string' || taskName.trim() === '') throw new TypeError('taskName is required');
  const minutes = Number(everyMinutes);
  if (!Number.isInteger(minutes) || minutes < 1) throw new TypeError('everyMinutes must be a positive integer');
  return [
    '/Create', '/F',
    '/SC', 'MINUTE',
    '/MO', String(minutes),
    '/TN', taskName,
    '/TR', hiddenTaskCommandLine(vbsPath),
  ];
}
